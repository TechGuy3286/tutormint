-- 03_taxonomy.sql
-- Replace the legacy taxonomy_* tables with the canonical slug-based schema
-- from supabase/seed/seed_taxonomy.sql.
--
-- DESTRUCTIVE, approved: drops taxonomy_master (907 rows) and
-- taxonomy_categories (73 rows). taxonomy_levels and taxonomy_subjects were
-- already empty. The old shape ("Level 1"/"Level 2"/"Level 3") is unrelated to
-- the seed's (category_slug/level_slug/subject_slug), so ALTER cannot bridge
-- them. Pre-drop data is in supabase/backups/before-t1.sql.
--
-- The only FKs on these tables were internal (taxonomy_subjects -> levels,
-- taxonomy_categories self-reference); nothing outside the taxonomy set
-- depends on them, and no views reference them.
--
-- This file is generated verbatim from supabase/seed/seed_taxonomy.sql. Two
-- bugs were fixed in that seed (see 12_taxonomy_leaf_type.sql) and are already
-- reflected below:
--   * 120 empty subject_slug cells were emitted as the literal string 'nan',
--     which violated taxonomy_master_subject_slug_fkey. They are now null.
--   * those same 120 level-leaf rows were emitted as leaf_type='subject'.
--     They are now leaf_type='level', matching CLAUDE.md. Row count is
--     unchanged at 896 (120 level + 776 subject).
--
-- lib/taxonomy.ts reads these tables. Idempotent: drop if exists, then the
-- seed's own create-if-not-exists and on-conflict upserts.
--
-- CAUTION on re-running: the drops are CASCADE. Today nothing outside the
-- taxonomy set references these tables -- tutor_subjects.subject_slug and
-- job_subjects.subject_slug deliberately carry no FK yet -- so a re-run is
-- safe. If such an FK is added later, a re-run would silently cascade-drop it;
-- re-add it after re-seeding.

drop table if exists public.taxonomy_master     cascade;
drop table if exists public.taxonomy_subjects   cascade;
drop table if exists public.taxonomy_levels     cascade;
drop table if exists public.taxonomy_categories cascade;

