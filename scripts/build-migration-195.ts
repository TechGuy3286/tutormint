/**
 * scripts/build-migration-195.ts — writes supabase/migrations/195_applications_v31.sql
 * from the code defaults, so the seeded templates are byte-for-byte the v3
 * wording (lib/applicationTemplatesCore APP_TEMPLATES).
 *   npx tsx scripts/build-migration-195.ts
 */
import { writeFileSync } from 'node:fs'
import { APP_TEMPLATES } from '../lib/applicationTemplatesCore'

/** A dollar-quoted SQL literal that cannot clash with the body. */
function lit(text: string): string {
  let tag = 'tm'
  while (text.includes(`$${tag}$`)) tag += 'x'
  return `$${tag}$${text}$${tag}$`
}

const rows = APP_TEMPLATES.map((t) => `  (${lit(t.key)}, ${lit(t.title)}, ${lit(t.title)}, ${lit(t.defaultBody)})`).join(',\n')

const sql = `-- 195_applications_v31.sql — Applications v3.1 (owner, 23 Oct 2026).
--
-- Additive and re-runnable. Generated by scripts/build-migration-195.ts from
-- lib/applicationTemplatesCore (do not hand-edit the template bodies).
--
-- 1. The Applied-stage message counts as forwarding (lib/applicationFollowUps).
--    Its Undo marks things undone, never deletes:
--      applicant_forwards.undone_at / undone_by   a forward taken back;
--      application_follow_ups.forward_id          the forward that follow-up made;
--      application_follow_ups.restore             the application's stage fields
--                                                 before it moved (for Undo).
--    No policy changes: both tables stay admin-read, service-role writes.
--
-- 2. The 8 Applications messages become editable templates in Team inbox →
--    Templates, seeded with exactly the v3 wording (insert only if missing, so
--    an edit is never overwritten by a re-run).
--
-- 3. The support WhatsApp number every Applications message ends with is read
--    from app_settings 'support.whatsapp' (already present on production; the
--    insert only fills a fresh database). Owner-only edit (the route checks).

alter table public.applicant_forwards
  add column if not exists undone_at timestamptz,
  add column if not exists undone_by uuid references auth.users(id) on delete set null;

alter table public.application_follow_ups
  add column if not exists forward_id uuid references public.applicant_forwards(id) on delete set null,
  add column if not exists restore jsonb;

create index if not exists application_follow_ups_forward_idx
  on public.application_follow_ups (forward_id) where forward_id is not null;

insert into public.admin_message_templates (key, title, subject, body) values
${rows}
on conflict (key) do nothing;

insert into public.app_settings (key, value) values ('support.whatsapp', '923215872222')
on conflict (key) do nothing;
`

writeFileSync('supabase/migrations/195_applications_v31.sql', sql)
console.log('wrote supabase/migrations/195_applications_v31.sql')
