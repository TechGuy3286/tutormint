/**
 * scripts/build-default-avatars.ts — npx tsx scripts/build-default-avatars.ts
 *
 * Makes the web copies of the owner's branded default avatars (5 Nov 2026).
 * Sources stay where the owner put them: public/male-dummy.png and
 * public/fe-male-dummy.png (1080×1080, a mint circle on white).
 *
 * Each source is cut to the mint circle (the white margin removed, so a round
 * frame shows the circle edge to edge), then written as:
 *   public/avatars/default-<gender>-512.webp / .png
 *   public/avatars/default-<gender>-128.webp / .png
 * and the 512 PNG is embedded as base64 in lib/social/defaultAvatarData.ts for
 * the social render (satori) and the CV PDF, which cannot read public/ on Vercel.
 *
 * Re-runnable. Commit the outputs with this script.
 */
import { mkdirSync, readFileSync, writeFileSync, statSync } from 'node:fs'
import sharp from 'sharp'

const SOURCES = { male: 'public/male-dummy.png', female: 'public/fe-male-dummy.png' } as const
const SIZES = [512, 128] as const

async function circleBox(file: string) {
  const { data, info } = await sharp(file).removeAlpha().raw().toBuffer({ resolveWithObject: true })
  let minX = info.width, minY = info.height, maxX = -1, maxY = -1
  for (let y = 0; y < info.height; y++) {
    for (let x = 0; x < info.width; x++) {
      const i = (y * info.width + x) * info.channels
      // Not white (the margin is ~255,255,255; the mint fill is ~213,240,222).
      if (data[i] < 240 || data[i + 1] < 240 || data[i + 2] < 240) {
        if (x < minX) minX = x
        if (x > maxX) maxX = x
        if (y < minY) minY = y
        if (y > maxY) maxY = y
      }
    }
  }
  // A square around the circle's centre, inset 1% so no white fringe survives.
  const cx = (minX + maxX) / 2
  const cy = (minY + maxY) / 2
  const side = Math.floor(Math.min(maxX - minX, maxY - minY) * 0.98)
  const left = Math.max(0, Math.round(cx - side / 2))
  const top = Math.max(0, Math.round(cy - side / 2))
  return { left, top, width: Math.min(side, info.width - left), height: Math.min(side, info.height - top) }
}

async function main() {
  mkdirSync('public/avatars', { recursive: true })
  const embedded: Record<string, string> = {}
  for (const [gender, file] of Object.entries(SOURCES)) {
    const box = await circleBox(file)
    for (const size of SIZES) {
      const base = sharp(file).extract(box).resize(size, size, { kernel: 'lanczos3' })
      const webp = `public/avatars/default-${gender}-${size}.webp`
      const png = `public/avatars/default-${gender}-${size}.png`
      await base.clone().webp({ quality: 82, effort: 6 }).toFile(webp)
      await base.clone().median(3).png({ palette: true, colours: 24, dither: 0, compressionLevel: 9, effort: 10 }).toFile(png)
      for (const f of [webp, png]) console.log(`${f}  ${(statSync(f).size / 1024).toFixed(1)} KB`)
      if (size === 512) {
        const buf = readFileSync(png)
        embedded[gender] = `data:image/png;base64,${buf.toString('base64')}`
      }
    }
  }
  const out = `// lib/social/defaultAvatarData.ts — GENERATED by scripts/build-default-avatars.ts. Do not edit.
//
// The branded default avatars (512×512 PNG) as data URIs, for the social render
// (satori) and the CV PDF (react-pdf): both embed a data URI, and public/ is not
// on the Vercel function filesystem. Same pixels as public/avatars/default-*-512.png.

export const DEFAULT_AVATAR_PNG_DATA_URI = {
  male: ${JSON.stringify(embedded.male)},
  female: ${JSON.stringify(embedded.female)},
} as const
`
  writeFileSync('lib/social/defaultAvatarData.ts', out)
  console.log('lib/social/defaultAvatarData.ts written')
}

main().catch((e) => { console.error(e); process.exit(1) })
