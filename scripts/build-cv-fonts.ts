/**
 * scripts/build-cv-fonts.ts — writes lib/cv/urduFont.ts from
 * assets/fonts/noto-naskh-arabic/noto-naskh-arabic-arabic-400-normal.woff
 * (Noto Naskh Arabic, SIL Open Font License 1.1 — assets/fonts/noto-naskh-arabic/
 * OFL.txt; the @fontsource 5.3.0 "arabic" subset, which covers every Urdu
 * letter in U+0600–06FF and the presentation forms).
 *
 * The CV PDF registers it as the fallback face after Plus Jakarta Sans, so Urdu
 * profile text prints as Urdu, never as boxes.
 *   npx tsx scripts/build-cv-fonts.ts
 */
import { readFileSync, writeFileSync } from 'node:fs'

const src = 'assets/fonts/noto-naskh-arabic/noto-naskh-arabic-arabic-400-normal.woff'
const b64 = readFileSync(src).toString('base64')
const out = `// lib/cv/urduFont.ts — GENERATED by scripts/build-cv-fonts.ts. Do not edit.
//
// Noto Naskh Arabic 400, SIL Open Font License 1.1 (assets/fonts/noto-naskh-arabic/
// OFL.txt). The @fontsource "arabic" subset as base64 WOFF — the CV PDF's
// fallback face for Urdu text.

export const NASKH_400_B64 =
  '${b64}'
`
writeFileSync('lib/cv/urduFont.ts', out)
console.log(`wrote lib/cv/urduFont.ts (${b64.length} base64 chars)`)
