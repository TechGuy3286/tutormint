/**
 * scripts/build-social-fonts.ts — regenerates lib/social/fonts.ts.
 *
 *   npx tsx scripts/build-social-fonts.ts
 *
 * Plus Jakarta Sans (SIL Open Font License 1.1, assets/fonts/plus-jakarta-sans/
 * OFL.txt; latin subset from @fontsource/plus-jakarta-sans 5.3.0) in three
 * weights, embedded as base64 so the social render needs no file at runtime
 * (public/ is not on the Vercel function filesystem). It also writes each
 * weight's advance widths for printable ASCII, so lib/social/fit.ts can wrap and
 * shrink a headline or a name before satori draws it.
 */
import { readFileSync, writeFileSync } from 'node:fs'
import path from 'node:path'
// @ts-expect-error fontkit ships no bundled types here
import * as fontkit from 'fontkit'

const root = path.join(__dirname, '..')
const dir = path.join(root, 'assets/fonts/plus-jakarta-sans')
const weights = [500, 700, 800] as const

let out = `// lib/social/fonts.ts — GENERATED by scripts/build-social-fonts.ts. Do not edit.
//
// Plus Jakarta Sans, SIL Open Font License 1.1 (assets/fonts/plus-jakarta-sans/
// OFL.txt). Latin subset, weights 500 / 700 / 800, as base64 WOFF, plus each
// weight's advance width (in em) for printable ASCII.

`
const widths: Record<number, Record<string, number>> = {}
for (const w of weights) {
  const file = path.join(dir, `plus-jakarta-sans-latin-${w}-normal.woff`)
  const buf = readFileSync(file)
  out += `export const JAKARTA_${w}_B64 =\n  '${buf.toString('base64')}'\n\n`
  const font = fontkit.create(buf)
  const table: Record<string, number> = {}
  for (let c = 32; c < 127; c++) {
    const ch = String.fromCharCode(c)
    const run = font.layout(ch)
    table[ch] = Math.round((run.advanceWidth / font.unitsPerEm) * 1000) / 1000
  }
  widths[w] = table
}
out += `/** Advance width in em, per weight, for printable ASCII. */\nexport const JAKARTA_WIDTHS: Record<500 | 700 | 800, Record<string, number>> = ${JSON.stringify(widths)}\n`
writeFileSync(path.join(root, 'lib/social/fonts.ts'), out)
console.log('wrote lib/social/fonts.ts')
